// `cage export-test`: a Playwright Test file that replays the minimal failing configuration from fixtures.
// Output depends only on @playwright/test; the replay logic is inlined (mirrors run.ts + replay.ts).
import { applyConfig } from './compose.ts';
import { align } from './factors.ts';
import { ORDER_GAP_MS } from './replay.ts';
import type { Bundle } from './types.ts';

export type Expect = 'fixed' | 'broken';

/** Files (relative path → content) for a standalone repro directory. */
export function exportTest(b: Bundle, expect: Expect = 'fixed'): Record<string, string> {
  const on = b.result.minimalSets[0] ?? b.factors.map((f) => f.id);
  const applied = applyConfig(b.bad, b.good, align(b.bad, b.good), b.factors, { on });
  const { file, ...builtins } = b.manifest.oracle;
  const plan = {
    sentence: b.result.sentence,
    expect,
    baseURL: b.manifest.baseOrigin,
    env: applied.env,
    storage: applied.storage,
    responses: [...applied.plan.responses.entries()],
    orders: applied.plan.orders,
    allowUnmatched: b.manifest.allowUnmatched,
    apiGlobs: b.manifest.apiGlobs,
    oracle: builtins,
    freezeRandom: b.manifest.freezeRandom,
    freezeTime: b.manifest.freezeTime,
  };
  const files: Record<string, string> = {
    'fixtures/plan.ts': `// Generated by cage export-test. Minimal failing configuration: ${on.length} factor(s) observed.\nexport default ${JSON.stringify(plan, null, 2)};\n`,
    'flow.ts': b.flowSource,
    'cage-repro.spec.ts': SPEC.replace('__ORACLE_IMPORT__', file && b.oracleSource ? "import fileOracle from './oracle';" : 'const fileOracle = null;').replace('__GAP__', String(ORDER_GAP_MS)),
    'playwright.config.ts': `// Generated by cage export-test.\nexport default { testDir: '.', timeout: 60_000, workers: 1 };\n`,
    'README.md': `# cage repro\n\n${b.result.sentence}\n\nRun against your app (PowerShell):\n\n\`\`\`powershell\n$env:CAGE_BASE_URL = "${b.manifest.baseOrigin}"\nnpx playwright test\n\`\`\`\n\nExpectation: **${expect}**. ${expect === 'fixed' ? 'Fails while the bug exists, passes once it is fixed.' : 'Passes while the known bug still reproduces.'}\n`,
  };
  if (file && b.oracleSource) files['oracle.ts'] = b.oracleSource;
  return files;
}

const SPEC = `// Generated by cage export-test. Needs only @playwright/test.
/* eslint-disable */
import { test, expect } from '@playwright/test';
import flow from './flow';
__ORACLE_IMPORT__
import plan from './fixtures/plan';

type Served = { status: number; headers: Record<string, string>; body: string; bodyEncoding: 'utf8' | 'base64'; latencyMs: number; abort?: boolean };
const P = plan as any;
const VOLATILE = ['_', 'ts', 't', 'nonce', 'cacheBust'];
const SECRET = /token|secret|password|passwd|session|auth|jwt|key/i;
const DROP = new Set(['content-length', 'content-encoding', 'transfer-encoding', 'connection', 'keep-alive']);
const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

function key(method: string, url: string, base: string): string {
  const u = new URL(url, base);
  const params = [...u.searchParams].filter(([k]) => !VOLATILE.includes(k) && !SECRET.test(k));
  params.sort(([a, av], [b, bv]) => (a === b ? (av < bv ? -1 : av > bv ? 1 : 0) : a < b ? -1 : 1));
  const qs = params.length ? '?' + new URLSearchParams(params).toString() : '';
  const origin = u.origin === new URL(base).origin ? '' : u.origin;
  return method.toUpperCase() + ' ' + origin + u.pathname + qs;
}
function glob(g: string): RegExp {
  let re = '';
  for (let i = 0; i < g.length; i++) {
    const c = g[i]!;
    if (c === '*') { if (g[i + 1] === '*') { re += '.*'; i++; } else re += '[^/]*'; }
    else if (c === '?') re += '.';
    else re += c.replace(/[.+^\${}()|[\\]\\\\]/g, '\\\\$&');
  }
  return new RegExp('^' + re + '$');
}
const any = (url: string, globs: string[]) => globs.some((g) => glob(g).test(url));

test.use({
  serviceWorkers: 'block',
  viewport: P.env.viewport,
  locale: P.env.locale,
  timezoneId: P.env.timezoneId,
  ...(P.env.userAgent ? { userAgent: P.env.userAgent } : {}),
});

test('cage repro (expect ' + P.expect + '): ' + P.sentence.slice(0, 120), async ({ page, context }) => {
  const baseURL = process.env.CAGE_BASE_URL ?? P.baseURL;
  const origin = new URL(baseURL).origin;
  const responses = new Map<string, Served>(P.responses);
  const counts = new Map<string, number>();
  const unmatched: string[] = [];
  const consoleErrors: string[] = [];
  const pageErrors: string[] = [];
  const requests: { method: string; url: string; key: string; status: number; body: string }[] = [];
  const delivered = new Map<string, { p: Promise<void>; r: () => void }>();
  const gate = (t: string) => {
    let g = delivered.get(t);
    if (!g) { let r!: () => void; const p = new Promise<void>((res) => (r = res)); g = { p, r }; delivered.set(t, g); }
    return g;
  };

  if (P.storage.cookies.length) await context.addCookies(P.storage.cookies.map((c: any) => (c.domain ? { ...c, path: c.path ?? '/' } : { name: c.name, value: c.value, url: origin })));
  if (P.freezeRandom) await context.addInitScript('(() => { let s = 0x2f6b1d; Math.random = () => { s = (s + 0x6d2b79f5) | 0; let t = Math.imul(s ^ (s >>> 15), 1 | s); t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296; }; })();');
  if (P.freezeTime) await page.clock.install({ time: new Date('2026-01-01T00:00:00Z') });
  page.setDefaultTimeout(10_000);
  page.on('console', (m) => { if (m.type() === 'error') consoleErrors.push(m.text()); });
  page.on('pageerror', (e) => pageErrors.push(e.message));

  await page.route('**/*', async (route, request) => {
    if (request.url() === origin + '/__cage_seed__') return route.fulfill({ status: 200, contentType: 'text/html', body: '<!doctype html><title>seed</title>' });
    const t = request.resourceType();
    const isApi = P.apiGlobs.length ? any(request.url(), P.apiGlobs) : t === 'fetch' || t === 'xhr';
    if (!isApi) return route.continue();
    const k = key(request.method(), request.url(), baseURL);
    const nth = counts.get(k) ?? 0;
    counts.set(k, nth + 1);
    const target = k + '#' + nth;
    const s = responses.get(target);
    try {
      if (!s) {
        if (any(request.url(), P.allowUnmatched)) return route.continue();
        unmatched.push(target);
        return route.fulfill({ status: 599, contentType: 'text/plain', body: 'cage: no recorded response for ' + target });
      }
      if (s.abort) { gate(target).r(); return route.abort('failed'); }
      if (s.latencyMs > 0) await sleep(s.latencyMs);
      for (const o of P.orders) {
        if (o.second !== target) continue;
        await Promise.race([gate(o.first).p, sleep(5000)]);
        await sleep(__GAP__);
      }
      requests.push({ method: request.method(), url: request.url(), key: k, status: s.status, body: s.bodyEncoding === 'utf8' ? s.body : '' });
      const headers = Object.fromEntries(Object.entries(s.headers).filter(([h]) => !DROP.has(h.toLowerCase())));
      await route.fulfill({ status: s.status, headers, body: Buffer.from(s.body, s.bodyEncoding) });
      gate(target).r();
    } catch (e) {
      if (!/closed|disposed/i.test((e as Error).message)) throw e;
    }
  });

  const ls = P.storage.localStorage, ss = P.storage.sessionStorage;
  if (Object.keys(ls).length || Object.keys(ss).length) {
    await page.goto(origin + '/__cage_seed__');
    await page.evaluate(([l, s]) => {
      for (const [k, v] of Object.entries(l)) window.localStorage.setItem(k, v as string);
      for (const [k, v] of Object.entries(s)) window.sessionStorage.setItem(k, v as string);
    }, [ls, ss]);
  }

  const reasons: string[] = [];
  try {
    await flow({ page, baseURL } as any);
  } catch (e) {
    reasons.push('flow threw: ' + (e as Error).message.split('\\n')[0]);
  }
  if (!reasons.length) {
    const o = P.oracle;
    if (o.failOnUncaught && pageErrors.length) reasons.push('uncaught: ' + pageErrors[0]);
    for (const re of o.failOnConsole ?? []) { const hit = consoleErrors.find((m) => new RegExp(re).test(m)); if (hit) reasons.push('console: ' + hit); }
    if (o.failOnTextMissing?.length) { const text = await page.locator('body').innerText(); for (const t of o.failOnTextMissing) if (!text.includes(t)) reasons.push('text missing: ' + t); }
    for (const css of o.failOnSelectorMissing ?? []) if ((await page.locator(css).count()) === 0) reasons.push('selector missing: ' + css);
    if (fileOracle) { const r = await (fileOracle as any)({ page, consoleErrors, pageErrors, requests }); if (r.failed) reasons.push(r.reason ?? 'oracle reported failure'); }
  }
  expect(unmatched, 'requests with no recorded response').toEqual([]);
  if (P.expect === 'fixed') expect(reasons, 'the failure still reproduces').toEqual([]);
  else expect(reasons.length, 'the known bug no longer reproduces').toBeGreaterThan(0);
});
`;
